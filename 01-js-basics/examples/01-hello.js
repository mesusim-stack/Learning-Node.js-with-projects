// Anything after // is a COMMENT.
// Comments are notes for humans — Node ignores them completely.

// console.log() prints text to the terminal, then moves to the next line.
// The text between the quotes is called a STRING.
console.log("Hello, world!");

// You can print several things in one line by separating them with commas.
console.log("My name is", "Haacha");

// Numbers do NOT need quotes. This line does math, then prints the result.
console.log("2 + 3 =", 2 + 3);

